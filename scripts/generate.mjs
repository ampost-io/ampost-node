#!/usr/bin/env node
/**
 * Generates the SDK's typed layer from the Ampost OpenAPI document.
 *
 *   npm run generate                                   # from the committed openapi.json
 *   npm run generate -- --spec https://api.ampost.io/openapi.json
 *   npm run generate -- --spec ../path/to/openapi.json
 *
 * With --spec, the document is first saved as openapi.json, so the snapshot and the code always match.
 * Output (never edit by hand):
 *   src/generated/schema.ts     paths, operations and components, by openapi-typescript (a field with a
 *                               `default` stays optional: request bodies share these schemas)
 *   src/generated/types.ts      readable aliases: Post, PostsCreateBody, PostsListQuery, ...
 *   src/generated/resources.ts  one class per tag (client.posts, client.accounts, ...) with a method per operation
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SNAPSHOT = join(ROOT, "openapi.json");
const OUT = join(ROOT, "src", "generated");
const HEADER = "// Generated by scripts/generate.mjs from openapi.json. Do not edit by hand: run `npm run generate`.\n";
const HTTP_METHODS = ["get", "post", "put", "patch", "delete"];

/**
 * Method names that read better than the ones derived from the operationId (tag prefix stripped, camelCase).
 * A new operation needs no entry: it gets the derived name.
 */
const METHOD_NAMES = {
  media_upload_create: "createUpload",
  media_upload_status: "getUpload",
  accounts_connect_status: "getConnectRequest",
  queue_get: "getQueue",
  queue_update: "updateQueue",
  queue_slots: "getQueueSlots",
  analytics_posts: "listPosts",
  analytics_overview: "getOverview",
  analytics_followers: "listFollowers",
  webhooks_deliveries_list: "listDeliveries",
  docs_search: "search",
  feedback_submit: "submit",
};

const camel = (value) => value.replace(/[-_]+([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (value) => camel(value).replace(/^[a-z]/, (c) => c.toUpperCase());

async function loadSpec() {
  const flag = process.argv.indexOf("--spec");
  if (flag === -1) return readFileSync(SNAPSHOT, "utf8");
  const source = process.argv[flag + 1];
  if (!source) throw new Error("--spec needs a URL or a file path");
  let text;
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source);
    if (!response.ok) throw new Error(`GET ${source}: HTTP ${response.status}`);
    text = await response.text();
  } else {
    text = readFileSync(source, "utf8");
  }
  const snapshot = `${JSON.stringify(JSON.parse(text), null, 2)}\n`;
  writeFileSync(SNAPSHOT, snapshot);
  return snapshot;
}

function deref(spec, schema) {
  let current = schema;
  while (current && current.$ref) {
    const name = current.$ref.replace("#/components/schemas/", "");
    current = spec.components.schemas[name];
  }
  return current;
}

function docComment(lines, indent) {
  const text = lines
    .filter((line) => line !== undefined && line !== null)
    .join("\n")
    .replace(/\*\//g, "*\\/")
    .trim();
  const body = text.split("\n").map((line) => `${indent} *${line ? ` ${line}` : ""}`);
  return `${indent}/**\n${body.join("\n")}\n${indent} */\n`;
}

function collectOperations(spec) {
  const operations = [];
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const method of HTTP_METHODS) {
      const op = item[method];
      if (!op) continue;
      const tag = op.tags?.[0] ?? "default";
      const prefix = `${tag.replace(/-/g, "_")}_`;
      const id = op.operationId;
      const name = METHOD_NAMES[id] ?? camel(id.startsWith(prefix) ? id.slice(prefix.length) : id);
      const parameters = op.parameters ?? [];
      const pathParams = parameters.filter((p) => p.in === "path").map((p) => p.name);
      // Path parameters in the order the path names them.
      pathParams.sort((a, b) => path.indexOf(`{${a}}`) - path.indexOf(`{${b}}`));
      const queryParams = parameters.filter((p) => p.in === "query");
      const json = op.requestBody?.content?.["application/json"];
      const successStatus = Object.keys(op.responses).find((code) => /^2\d\d$/.test(code));
      const success = op.responses[successStatus]?.content?.["application/json"]?.schema;
      const resolved = deref(spec, success);
      const paginated =
        method === "get" &&
        queryParams.some((p) => p.name === "offset") &&
        resolved?.properties?.data?.type === "array" &&
        Boolean(resolved?.properties?.pagination);
      operations.push({
        id,
        tag,
        name,
        typeName: pascal(id),
        method: method.toUpperCase(),
        path,
        summary: op.summary,
        description: op.description,
        pathParams,
        hasQuery: queryParams.length > 0,
        queryRequired: queryParams.some((p) => p.required),
        hasBody: Boolean(json),
        bodyRequired: Boolean(op.requestBody?.required),
        successStatus,
        hasResponse: Boolean(success),
        idempotent: parameters.some((p) => p.in === "header" && p.name.toLowerCase() === "idempotency-key"),
        paginated,
      });
    }
  }
  return operations;
}

function typesFile(spec, operations) {
  const lines = [HEADER, 'import type { components, operations } from "./schema.js";', ""];
  const taken = new Set();
  const declare = (name, type, doc) => {
    if (taken.has(name)) throw new Error(`Two generated types are named ${name}; add a METHOD_NAMES entry or rename`);
    taken.add(name);
    if (doc) lines.push(docComment([doc], ""));
    lines.push(`export type ${name} = ${type};`);
  };
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    declare(name, `components["schemas"][${JSON.stringify(name)}]`, schema.description?.split("\n")[0]);
  }
  lines.push("");
  for (const op of operations) {
    const ref = `operations[${JSON.stringify(op.id)}]`;
    if (op.hasQuery) declare(`${op.typeName}Query`, `NonNullable<${ref}["parameters"]["query"]>`);
    if (op.hasBody) declare(`${op.typeName}Body`, `NonNullable<${ref}["requestBody"]>["content"]["application/json"]`);
    declare(
      `${op.typeName}Response`,
      op.hasResponse ? `${ref}["responses"][${op.successStatus}]["content"]["application/json"]` : "void",
    );
  }
  return `${lines.join("\n")}\n`;
}

function methodSource(op) {
  const args = op.pathParams.map((name) => `${name}: string`);
  if (op.hasBody) args.push(`body${op.bodyRequired ? "" : "?"}: types.${op.typeName}Body`);
  if (op.hasQuery) args.push(`query${op.queryRequired ? "" : "?"}: types.${op.typeName}Query`);
  args.push(`options?: ${op.idempotent ? "IdempotentRequestOptions" : "RequestOptions"}`);

  const pathExpr = op.pathParams.length
    ? `\`${op.path.replace(/\{(\w+)\}/g, (_, name) => `\${encodePathParam(${name})}`)}\``
    : JSON.stringify(op.path);
  const fields = [`method: ${JSON.stringify(op.method)}`, `path: ${pathExpr}`];
  if (op.hasQuery) fields.push("query");
  if (op.hasBody) fields.push("body");
  if (op.idempotent) fields.push("idempotent: true");
  const spec = `{ ${fields.join(", ")} }`;
  const response = `types.${op.typeName}Response`;
  const call = op.paginated
    ? `return this.transport.paginate<${response}>(${spec}, options);`
    : `return this.transport.request<${response}>(${spec}, options);`;
  const returns = op.paginated ? `PagePromise<${response}>` : `Promise<${response}>`;

  const doc = docComment(
    [
      op.summary,
      "",
      op.description,
      "",
      `\`${op.method} ${op.path}\``,
      op.idempotent ? "Sends an `Idempotency-Key` (yours, or a generated one kept across retries)." : undefined,
      op.paginated ? "Await it for one page, or iterate it with `for await` to walk every item across pages." : undefined,
    ],
    "  ",
  );
  return `${doc}  ${op.name}(${args.join(", ")}): ${returns} {\n    ${call}\n  }\n`;
}

function resourcesFile(operations) {
  const tags = [...new Set(operations.map((op) => op.tag))];
  const out = [
    HEADER,
    'import type { IdempotentRequestOptions, ListResponse, RequestOptions, RequestSpec, Transport } from "../core.js";',
    'import { encodePathParam } from "../core.js";',
    'import type { PagePromise } from "../pagination.js";',
    'import type * as types from "./types.js";',
    "",
  ];
  for (const tag of tags) {
    const names = new Set();
    out.push(`/** \`${tag}\` operations. */`);
    out.push(`export class ${pascal(tag)} {`);
    out.push("  constructor(protected readonly transport: Transport) {}\n");
    for (const op of operations.filter((o) => o.tag === tag)) {
      if (names.has(op.name)) throw new Error(`${tag} has two methods named ${op.name}; add a METHOD_NAMES entry`);
      names.add(op.name);
      out.push(methodSource(op));
    }
    out[out.length - 1] = out[out.length - 1].replace(/\n$/, "");
    out.push("}\n");
  }
  out.push("/** Every resource of the API, one property per tag. `Ampost` extends this. */");
  out.push("export abstract class AmpostResources implements Transport {");
  for (const tag of tags) out.push(`  readonly ${camel(tag)}: ${pascal(tag)} = new ${pascal(tag)}(this);`);
  out.push("");
  out.push("  abstract request<T>(spec: RequestSpec, options?: IdempotentRequestOptions): Promise<T>;");
  out.push("  abstract paginate<T extends ListResponse>(spec: RequestSpec, options?: RequestOptions): PagePromise<T>;");
  out.push("}");
  out.push("");
  out.push("/** Every operation, for tests and tooling. */");
  out.push("export const OPERATIONS = [");
  for (const op of operations) {
    out.push(
      `  { operationId: ${JSON.stringify(op.id)}, resource: ${JSON.stringify(camel(op.tag))}, method: ${JSON.stringify(op.name)}, httpMethod: ${JSON.stringify(op.method)}, path: ${JSON.stringify(op.path)}, idempotent: ${op.idempotent}, paginated: ${op.paginated} },`,
    );
  }
  out.push("] as const;");
  return `${out.join("\n")}\n`;
}

const text = await loadSpec();
const spec = JSON.parse(text);
const operations = collectOperations(spec);
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "schema.ts"), HEADER + "\n" + astToString(await openapiTS(spec, { defaultNonNullable: false })));
writeFileSync(join(OUT, "types.ts"), typesFile(spec, operations));
writeFileSync(join(OUT, "resources.ts"), resourcesFile(operations));
console.log(`Generated ${operations.length} operations from ${spec.info.title} ${spec.info.version}`);
